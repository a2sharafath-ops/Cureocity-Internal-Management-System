import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { createClient } from "@supabase/supabase-js";
import {
  ASSISTANT_E2E_ACCOUNTS,
  ASSISTANT_E2E_CREDENTIAL_FILE,
  ASSISTANT_E2E_SCOPE,
  credentialPrefix,
  isSafeDevelopmentAppUrl,
  isSafeDevelopmentSupabaseUrl,
  parseEnvFile,
  syntheticEmail,
  syntheticName,
} from "./dev-assistant-test-contract.mjs";

const projectRoot = process.cwd();
const developmentEnvPath = resolve(projectRoot, ".env.development.local");
const credentialPath = resolve(projectRoot, ASSISTANT_E2E_CREDENTIAL_FILE);

if (!existsSync(developmentEnvPath)) {
  throw new Error("Missing .env.development.local. Start from the Cureocity repository and configure AWS Development first.");
}

const developmentEnv = {
  ...parseEnvFile(readFileSync(developmentEnvPath, "utf8")),
  ...process.env,
};

if (!isSafeDevelopmentSupabaseUrl(developmentEnv.NEXT_PUBLIC_SUPABASE_URL ?? "")) {
  throw new Error("Refusing to provision: NEXT_PUBLIC_SUPABASE_URL must be the local AWS Development tunnel at 127.0.0.1:54321.");
}
if (!isSafeDevelopmentAppUrl(developmentEnv.NEXT_PUBLIC_APP_URL ?? "")) {
  throw new Error("Refusing to provision: NEXT_PUBLIC_APP_URL must be the local Development app at 127.0.0.1:3000.");
}
if (!developmentEnv.SUPABASE_SERVICE_ROLE_KEY) {
  throw new Error("Missing the Development-only SUPABASE_SERVICE_ROLE_KEY.");
}

const previousCredentials = existsSync(credentialPath)
  ? parseEnvFile(readFileSync(credentialPath, "utf8"))
  : {};

const admin = createClient(
  developmentEnv.NEXT_PUBLIC_SUPABASE_URL,
  developmentEnv.SUPABASE_SERVICE_ROLE_KEY,
  { auth: { persistSession: false, autoRefreshToken: false } },
);

async function listAllUsers() {
  const users = [];
  for (let page = 1; ; page += 1) {
    const { data, error } = await admin.auth.admin.listUsers({ page, perPage: 1000 });
    if (error) throw error;
    users.push(...data.users);
    if (data.users.length < 1000) return users;
  }
}

function passwordFor(slug) {
  const key = `${credentialPrefix(slug)}_PASSWORD`;
  return previousCredentials[key] || randomBytes(36).toString("base64url");
}

const users = await listAllUsers();
const credentials = [
  "# Local AWS Development synthetic Assistant accounts.",
  "# Generated by scripts/provision-dev-assistant-test-accounts.mjs.",
  "# Never commit or share this file.",
  `ASSISTANT_E2E_BASE_URL=${developmentEnv.NEXT_PUBLIC_APP_URL}`,
  `ASSISTANT_E2E_SCOPE=${ASSISTANT_E2E_SCOPE}`,
];
let created = 0;
let refreshed = 0;

for (const account of ASSISTANT_E2E_ACCOUNTS) {
  const email = syntheticEmail(account.slug);
  const name = syntheticName(account.role);
  const password = passwordFor(account.slug);
  const existing = users.find((user) => user.email?.toLowerCase() === email);
  let userId;

  if (existing) {
    if (existing.app_metadata?.synthetic_scope !== ASSISTANT_E2E_SCOPE) {
      throw new Error(`Refusing to manage ${account.role}: the expected synthetic email already belongs to an account outside this test scope.`);
    }
    const { data, error } = await admin.auth.admin.updateUserById(existing.id, {
      password,
      email_confirm: true,
      user_metadata: { ...existing.user_metadata, name, synthetic: true },
      app_metadata: { ...existing.app_metadata, synthetic_scope: ASSISTANT_E2E_SCOPE, synthetic_role: account.role },
    });
    if (error || !data.user) throw error ?? new Error(`Could not refresh the ${account.role} test account.`);
    userId = data.user.id;
    refreshed += 1;
  } else {
    const { data, error } = await admin.auth.admin.createUser({
      email,
      password,
      email_confirm: true,
      user_metadata: { name, synthetic: true },
      app_metadata: { synthetic_scope: ASSISTANT_E2E_SCOPE, synthetic_role: account.role },
    });
    if (error || !data.user) throw error ?? new Error(`Could not create the ${account.role} test account.`);
    userId = data.user.id;
    created += 1;
  }

  const { error: profileError } = await admin.from("profiles").upsert({
    id: userId,
    email,
    name,
    role: account.role,
    branch: "Kochi",
  });
  if (profileError) throw profileError;

  const prefix = credentialPrefix(account.slug);
  credentials.push(`${prefix}_EMAIL=${email}`);
  credentials.push(`${prefix}_PASSWORD=${password}`);
}

const expectedEmails = ASSISTANT_E2E_ACCOUNTS.map((account) => syntheticEmail(account.slug));
const { data: profiles, error: profileVerificationError } = await admin
  .from("profiles")
  .select("email, role")
  .in("email", expectedEmails);
if (profileVerificationError) throw profileVerificationError;

const verifiedRoles = new Set((profiles ?? []).map((profile) => `${profile.email}|${profile.role}`));
for (const account of ASSISTANT_E2E_ACCOUNTS) {
  if (!verifiedRoles.has(`${syntheticEmail(account.slug)}|${account.role}`)) {
    throw new Error(`Profile verification failed for ${account.role}.`);
  }
}

writeFileSync(credentialPath, `${credentials.join("\n")}\n`, { encoding: "utf8", mode: 0o600 });
chmodSync(credentialPath, 0o600);

console.log(`AWS Development Assistant test accounts ready: ${ASSISTANT_E2E_ACCOUNTS.length} roles (${created} created, ${refreshed} refreshed).`);
console.log(`Credentials were saved locally with mode 0600 in ${ASSISTANT_E2E_CREDENTIAL_FILE}; no credential values were printed.`);
