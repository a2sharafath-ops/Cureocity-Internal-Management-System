-- Approving the recipes that pass every check this app can make.
--
-- 499 of the 1,014 imported recipes, and only these: each one is priced
-- from its own ingredients against the food table — not quoted from INDB — and
-- clears every mechanical test.
--
--   * its figures agree with INDB's published ones to within 25%
--   * one serving is a plausible amount of food: under 1,200 kcal, under 90 g
--     of fat, under 75 g of protein
--   * its calories agree with its own carbohydrate, protein and fat by Atwater
--   * every ingredient is matched to the food table and weighed
--
-- WHAT THIS IS NOT. It is not a dietitian saying these recipes are right for a
-- client. Arithmetic cannot answer that: a sweet biscuit passes every test
-- above and still has no place on a chart for a client with PCOS. The audit
-- trail records the approver as machine-verified precisely so nobody later
-- mistakes it for clinical review, and every one can be withdrawn from the
-- Dish library in a click.
--
-- What it does buy is a working library that cannot put an arithmetically
-- wrong number on a chart, so the dietitian's judgement is spent on whether a
-- dish suits a client rather than on whether its figures add up.
--
-- The other 515 stay unapproved: 332 that quote INDB rather than computing,
-- 82 with no figures at all, and 101 that fail at least one test above.

