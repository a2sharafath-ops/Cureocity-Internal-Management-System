-- How many servings a recipe actually makes.
--
-- The import read INDB's `no_of_servings` as the number of portions and its
-- `size_of_servings` as part of the label. Both wrong. The two multiply: a
-- recipe with no_of_servings 2 and size_of_servings 4 makes EIGHT idlis, and
-- the per-serving figures INDB publishes are for ONE idli, not for four.
--
-- Checked rather than assumed. Dividing each recipe's computed total by the
-- figure INDB publishes for one serving gives the number of servings it must
-- make; that agrees with no_of_servings x size_of_servings on 600 of the 602
-- recipes where both can be worked out, and with no_of_servings alone on 431.
--
-- What it was doing to the library: every dish whose size_of_servings was
-- more than 1 had its computed figures inflated by that factor. Chapati came
-- out at 294 kcal against a published 73, four idlis at 138 against 34 — and
-- each of those disagreements was then flagged as a recipe needing a look,
-- when the recipe was fine and the servings count was not.
--
-- The labels are corrected with them: a serving is one chapati, not four.
--
-- 82 recipes have no usable serving figures and are left alone.

